#include <iostream>     // Бібліотека для введення та виведення даних

using namespace std;    // Дозволяє використовувати cout і cin без std::

int main()
{
    // Оголошення змінних
    float  R;           // Радіус круга
    double L;           // Довжина кола
    double S;           // Площа круга

    // Стала π (число Пі)
    const double PI = 3.141592653589793;

    // Введення радіуса
    cout << "Введіть радіус R: ";
    cin >> R;

    // Обчислення довжини кола
    // Формула: L = 2 * π * R
    L = 2 * PI * R;

    // Обчислення площі круга
    // Формула: S = π * R²
    S = PI * R * R;

    // Виведення результатів
    cout << "Довжина кола L = " << L << endl;
    cout << "Площа круга S = " << S << endl;

    return 0;           // Завершення роботи програми
}